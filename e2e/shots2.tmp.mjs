import { chromium, devices } from "@playwright/test";
const out = "/private/tmp/claude-501/-Users-tylerallen-Documents-projects/ac6b71dd-bfd7-4879-9073-28712f9229e0/scratchpad/sat-shots";
const browser = await chromium.launch();
for (const [name, opts, scheme] of [["phone", { ...devices["iPhone 13"], viewport: { width: 390, height: 844 } }, "light"], ["desktop", { viewport: { width: 1360, height: 860 } }, "dark"]]) {
  const context = await browser.newContext({ ...opts, colorScheme: scheme, serviceWorkers: "block" });
  const page = await context.newPage();
  await page.goto(`http://localhost:8905/maps?lat=54.58&lon=-3.14&z=${name === "phone" ? 11.6 : 12.2}`);
  await page.locator('.outpost-map[data-map-idle="true"]').waitFor({ timeout: 30000 });
  await page.getByRole("tab", { name: "Offline maps" }).click();
  await page.waitForTimeout(500);
  await page.screenshot({ path: `${out}/offline-section-${name}-${scheme}.png`, fullPage: false });
  await page.getByRole("region", { name: "Satellite imagery" }).getByRole("button", { name: "Choose an area" }).first().click();
  await page.getByRole("button", { name: "Use the current view" }).click();
  await page.getByRole("textbox", { name: "Name for this area" }).fill("Borrowdale");
  await page.waitForTimeout(400);
  await page.screenshot({ path: `${out}/area-${name}-${scheme}.png` });
  await page.getByRole("button", { name: "Find pictures" }).click();
  await page.getByRole("radio").first().waitFor({ timeout: 20000 });
  await page.screenshot({ path: `${out}/days-${name}-${scheme}.png` });
  await page.getByRole("radio", { name: /12 July 2026/ }).first().click();
  await page.getByRole("button", { name: "Continue" }).click();
  await page.getByText("To fetch").waitFor({ timeout: 30000 });
  await page.waitForTimeout(300);
  const scroll = await page.evaluate(() => [document.documentElement.scrollWidth, window.innerWidth]);
  console.log(name, "scrollWidth vs width", scroll);
  await page.screenshot({ path: `${out}/confirm-${name}-${scheme}.png` });
  const panel = page.locator(".scroll-quiet").filter({ hasText: "To fetch" });
  await panel.evaluate((el) => el.scrollTo(0, el.scrollHeight));
  await page.screenshot({ path: `${out}/confirm-bottom-${name}-${scheme}.png` });
  await context.close();
}
await browser.close();
