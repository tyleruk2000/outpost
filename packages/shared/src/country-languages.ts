/** The languages of a country, most used first, as ISO 639 codes; empty for a code GeoNames does not list. */
export function countryLanguages(code: string | null | undefined): string[] {
  if (!code) return [];
  const found = ownValue(LANGUAGES, code.toUpperCase());
  return found ? found.split(",") : [];
}
